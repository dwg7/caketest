-- Settlementsレイヤー: JICA研修対象9カ国それぞれについて、首都とは
-- 異なる文脈を持つ「特徴的な都市」を選び検証する(段階5)
--
-- 選定理由:
--   フィジー: ラバサ(スバとは別の島=バヌアレブ島。島嶼分散国土の実例)
--   ガボン: ポールジェンティル(石油産業都市、海沿いの経済拠点)
--   ラオス: ルアンパバーン(世界遺産都市、山岳部、観光文脈)
--   ナイジェリア: ラゴス(計画首都アブジャと対照的な、有機的な最大都市)
--   パプアニューギニア: ココポ(東ニューブリテン州、本島と別の島)
--   ルワンダ: ルバブ/ギセニ(コンゴ民主共和国ゴマとの国境双子都市)
--   シエラレオネ: ボー(内陸の第二都市)
--   東ティモール: オエクシ(インドネシア領内の飛び地)
--   トーゴ: ソコデ(北部の第二都市)
INSTALL spatial; LOAD spatial;
INSTALL httpfs; LOAD httpfs;

WITH regions(region, xmin, xmax, ymin, ymax) AS (
  VALUES
    ('フィジー(ラバサ、バヌアレブ島)', 179.25, 179.45, -16.55, -16.30),
    ('ガボン(ポールジェンティル)', 8.65, 8.90, -0.85, -0.60),
    ('ラオス(ルアンパバーン)', 102.05, 102.25, 19.80, 19.95),
    ('ナイジェリア(ラゴス)', 3.10, 3.60, 6.35, 6.70),
    ('パプアニューギニア(ココポ、東ニューブリテン州)', 152.15, 152.40, -4.45, -4.20),
    ('ルワンダ(ルバブ/ギセニ)', 29.15, 29.35, -1.80, -1.60),
    ('シエラレオネ(ボー)', -11.85, -11.60, 7.85, 8.05),
    ('東ティモール(オエクシ、飛び地)', 124.20, 124.55, -9.30, -9.10),
    ('トーゴ(ソコデ)', 1.02, 1.25, 8.88, 9.10)
)
SELECT r.region, s.place, count(*) AS n
FROM read_parquet('https://data.openstreetmap.us/layercake/settlements.parquet') s
JOIN regions r
  ON s.bbox.xmin BETWEEN r.xmin AND r.xmax AND s.bbox.ymin BETWEEN r.ymin AND r.ymax
GROUP BY r.region, s.place
ORDER BY r.region, n DESC;
